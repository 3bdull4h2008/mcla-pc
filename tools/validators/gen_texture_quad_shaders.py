#!/usr/bin/env python3
"""Regenerate tools/validators/texture_quad_shaders_gen.h.

Compiles tools/validators/shaders/texture_quad_{vs,ps}.hlsl with the vendored
DXC and embeds the DXIL containers as byte arrays, the same shape
src/renderer/test_shaders.h uses. Run after editing either .hlsl.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DXC = os.path.join(ROOT, ".research", "XenosRecomp", "thirdparty", "dxc-bin",
                   "bin", "x64", "dxc.exe")
SRC = os.path.join(ROOT, "tools", "validators", "shaders")
OUT = os.path.join(ROOT, "tools", "validators", "texture_quad_shaders_gen.h")


def compile_stage(entry, target, hlsl, fxc):
    cmd = [DXC, "-T", target, "-E", "main", "-Fo", fxc, os.path.join(SRC, hlsl)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0 or not os.path.exists(fxc):
        sys.exit("dxc failed for %s:\n%s\n%s" % (hlsl, r.stdout, r.stderr))


def arr(name, path):
    with open(path, "rb") as f:
        b = f.read()
    rows = [", ".join("0x%02X" % x for x in b[i:i + 12])
            for i in range(0, len(b), 12)]
    return "static const unsigned char %s[%d] = {\n    %s\n};\n" % (
        name, len(b), ",\n    ".join(rows))


def main():
    tmp = os.path.join(ROOT, "build")
    os.makedirs(tmp, exist_ok=True)
    vs_fxc = os.path.join(tmp, "tq_vs.fxc")
    ps_fxc = os.path.join(tmp, "tq_ps.fxc")
    compile_stage("vs", "vs_6_0", "texture_quad_vs.hlsl", vs_fxc)
    compile_stage("ps", "ps_6_0", "texture_quad_ps.hlsl", ps_fxc)
    text = (
        "#pragma once\n"
        "// Auto-generated by tools/validators/gen_texture_quad_shaders.py - do not edit.\n"
        "// Source: tools/validators/shaders/texture_quad_{vs,ps}.hlsl, vendored DXC,\n"
        "// shader model 6_0, entry 'main'.\n\n"
        + arr("kTextureQuadVs", vs_fxc) + "\n" + arr("kTextureQuadPs", ps_fxc))
    with open(OUT, "w", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (OUT, len(text)))


if __name__ == "__main__":
    main()
